"""Small, explicit contracts shared by persistence and command-line clients."""

from enum import StrEnum


class State(StrEnum):
    DRAFT = "DRAFT"
    PLANNING = "PLANNING"
    AWAITING_PLAN_APPROVAL = "AWAITING_PLAN_APPROVAL"
    FORMULATING = "FORMULATING"
    AWAITING_SCORE_APPROVAL = "AWAITING_SCORE_APPROVAL"
    CONFIGURING = "CONFIGURING"
    AWAITING_LAUNCH_APPROVAL = "AWAITING_LAUNCH_APPROVAL"
    QUEUED = "QUEUED"
    RUNNING = "RUNNING"
    EVALUATING = "EVALUATING"
    ANALYSING = "ANALYSING"
    AWAITING_REVISION_APPROVAL = "AWAITING_REVISION_APPROVAL"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


TRANSITIONS = {
    State.DRAFT: {State.PLANNING},
    State.PLANNING: {State.AWAITING_PLAN_APPROVAL},
    State.FORMULATING: {State.AWAITING_SCORE_APPROVAL},
    State.CONFIGURING: {State.AWAITING_LAUNCH_APPROVAL},
    State.QUEUED: {State.RUNNING},
    State.RUNNING: {State.EVALUATING},
    State.EVALUATING: {State.ANALYSING},
    State.ANALYSING: {State.COMPLETED, State.AWAITING_REVISION_APPROVAL},
}
APPROVAL_ROUTES = {
    State.AWAITING_PLAN_APPROVAL: ("plan", State.FORMULATING),
    State.AWAITING_SCORE_APPROVAL: ("score", State.CONFIGURING),
    State.AWAITING_LAUNCH_APPROVAL: ("launch", State.QUEUED),
    State.AWAITING_REVISION_APPROVAL: ("revision", State.PLANNING),
}
TERMINAL = {State.COMPLETED, State.FAILED, State.CANCELLED}


class PolicyError(ValueError):
    """An operation violates a campaign invariant."""
